// Плагин: русский промпт сжатия сессии
// Заменяет стандартный английский compaction prompt на русский,
// чтобы сводки сессий (Objective/Work State/...) были на русском.

export const RussianCompactionPlugin = async (ctx) => {
  return {
    "experimental.session.compacting": async (input, output) => {
      // Добавляем контекст: требование вести сводку на русском
      output.context.push(`## Языковое правило для сводки
ВСЯ сводка должна быть на русском языке. Никакого английского.
Исключения: технические термины (Jira, RFC, VSS, PowerBuilder, Sybase ASE, SQL, API, JSON, MCP, LLM, OpenCode), имена файлов, пути, кодовые идентификаторы.`)

      // Полностью заменяем промпт сжатия на русский
      output.prompt = `Ты — помощник, который создаёт сжатую сводку завершённой части разговора для продолжения работы.

## Твоя задача
Проанализировать предоставленный диалог и создать структурированную сводку, из которой новая языковая модель сможет продолжить работу.

## Формат сводки (строго соблюдай)

### Цель
Краткое описание (1-2 предложения) — какую общую задачу решает пользователь.

### Важные детали
Ключевая информация, которую нельзя потерять: пароли, пути, версии, конкретные числа, ограничения.

### Состояние работы
Таблица выполненного, активного и заблокированного.
Используй заголовки:
- **Выполнено** — что уже сделано
- **В работе** — что делается прямо сейчас
- **Заблокировано** — что ждёт внешних условий

### Следующие шаги
Нумерованный список конкретных следующих действий.

### Важные файлы
Список файлов с абсолютными путями, которые были изменены или активно используются.

## Правила
1. ВСЁ на русском языке
2. Кратко, но без потери важной информации
3. Сохраняй все пути, имена файлов, кодовые идентификаторы в исходном виде
4. Не придумывай того, чего не было в диалоге
5. Технические детали (логи, ошибки, конфигурации) описывай полностью
6. Если диалог пуст — так и напиши`
    }
  }
}
